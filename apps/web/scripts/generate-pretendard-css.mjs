// Writes src/styles/pretendard.css from the installed `pretendard` package.
//
// Pretendard draws Hangul here and nothing else: the Latin of the UI stays with the system fonts
// in the stack. The package's own style sheet covers Latin, Cyrillic and CJK as well, so every
// face it declares is narrowed to the part of its unicode-range that is Hangul, and a face with
// no Hangul in it is dropped. A browser then reaches Pretendard for Hangul only, and downloads
// just the subsets the text on the page needs.
//
// Run `pnpm --filter @skillcdn/web run generate:fonts` after changing the package version.

import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const packageFile = require.resolve("pretendard/package.json");
const packageRoot = dirname(packageFile);
const version = JSON.parse(readFileSync(packageFile, "utf8")).version;

const SOURCE = "dist/web/variable/pretendardvariable-dynamic-subset.css";
const SOURCE_DIR = SOURCE.slice(0, SOURCE.lastIndexOf("/") + 1);
const OUTPUT = join(dirname(fileURLToPath(import.meta.url)), "..", "src/styles/pretendard.css");

/** Hangul syllables, both jamo blocks, the extended jamo and the halfwidth forms. */
const HANGUL = [
  [0x1100, 0x11ff],
  [0x3130, 0x318f],
  [0xa960, 0xa97f],
  [0xac00, 0xd7ff],
  [0xffa0, 0xffdc],
];

const hex = (value) => value.toString(16).toUpperCase().padStart(4, "0");
const format = ([from, to]) => (from === to ? `U+${hex(from)}` : `U+${hex(from)}-${hex(to)}`);

function hangulPart(ranges) {
  const kept = [];
  for (const range of ranges) {
    for (const hangul of HANGUL) {
      const from = Math.max(range[0], hangul[0]);
      const to = Math.min(range[1], hangul[1]);
      if (from <= to) {
        kept.push([from, to]);
      }
    }
  }
  return kept;
}

const css = readFileSync(join(packageRoot, SOURCE), "utf8");
const faces = [...css.matchAll(/@font-face\s*\{([^}]*)\}/g)].map((match) => match[1]);
if (faces.length === 0) {
  throw new Error(`no @font-face found in ${SOURCE}: did the package change?`);
}

const blocks = [];
for (const face of faces) {
  const url = /url\(([^)]+)\)/.exec(face)?.[1];
  const weight = /font-weight:\s*([^;]+);/.exec(face)?.[1]?.trim();
  const ranges = [
    ...(/unicode-range:([^;]*);/.exec(face)?.[1] ?? "").matchAll(
      /U\+([0-9a-f]+)(?:-([0-9a-f]+))?/gi,
    ),
  ].map((match) => [parseInt(match[1], 16), parseInt(match[2] ?? match[1], 16)]);
  if (url === undefined || weight === undefined || ranges.length === 0) {
    throw new Error(`a face in ${SOURCE} is missing a url, a weight or a unicode-range`);
  }
  const hangul = hangulPart(ranges);
  if (hangul.length === 0) {
    continue;
  }
  // The build resolves this against the package and hashes the file into the bundle.
  const file = `pretendard/${SOURCE_DIR}${url.replace("./", "")}`;
  blocks.push(
    [
      "@font-face {",
      `  font-family: "Pretendard Variable";`,
      "  font-style: normal;",
      "  font-display: swap;",
      `  font-weight: ${weight};`,
      `  src: url("${file}") format("woff2-variations");`,
      `  unicode-range: ${hangul.map(format).join(", ")};`,
      "}",
    ].join("\n"),
  );
}

const header = [
  "/*",
  " * Generated by scripts/generate-pretendard-css.mjs from pretendard@" +
    version +
    ". Do not edit.",
  " * Regenerate with `pnpm --filter @skillcdn/web run generate:fonts`.",
  " *",
  " * Pretendard (SIL Open Font License 1.1) draws Hangul; the Latin of the UI stays with the",
  " * system fonts behind it in --font-sans. Each face is narrowed to its Hangul range, so a",
  " * browser never reaches Pretendard for anything else.",
  " */",
  "",
].join("\n");

writeFileSync(OUTPUT, `${header}${blocks.join("\n\n")}\n`);
process.stdout.write(`pretendard.css: ${blocks.length} of ${faces.length} faces kept
`);
