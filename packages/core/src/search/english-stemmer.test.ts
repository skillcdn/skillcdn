describe("stemEnglish", () => {
  it.each(STEMS)("stems %s to %s, as PostgreSQL does", (word, stem) => {
    expect(stemEnglish(word)).toBe(stem);
  });

  it("leaves a word of one or two letters, and takes the apostrophe off a possessive", () => {
    expect(stemEnglish("a")).toBe("a");
    expect(stemEnglish("go")).toBe("go");
    expect(stemEnglish("'tis")).toBe("tis");
    expect(stemEnglish("cat's")).toBe("cat");
    expect(stemEnglish("cats'")).toBe("cat");
  });

  it("leaves what has no English suffix, letters of other scripts included", () => {
    expect(stemEnglish("마케팅")).toBe("마케팅");
    expect(stemEnglish("skill-cdn")).toBe("skill-cdn");
    expect(stemEnglish("e-mail")).toBe("e-mail");
  });
});
